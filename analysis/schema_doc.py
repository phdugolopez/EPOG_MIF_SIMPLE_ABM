"""Generate docs/design/collector.md from model/schema.py.

    python -m analysis.schema_doc

tests/test_schema.py fails when the file is out of date: rerun this after any change to
the schema or to the comments of parameters.py.
"""

import re
from pathlib import Path

import parameters
from model.schema import RUN_ALIASES, SCHEMA, TABLES, parameter_columns

ROOT = Path(__file__).resolve().parent.parent
TARGET = ROOT / "docs" / "design" / "collector.md"

HEADER = """# Collector schema

> Generated by `python -m analysis.schema_doc` from `model/schema.py`; do not edit by
> hand. The specification is `collector-brief.md`, the plan `collector-plan.md`, the
> choices made `choices.md`.

`python run.py` writes seven tables to `outputs/` (or `--out DIR`), as CSV or Parquet
(`--format`), each with `run_id` as its first column. `macro` is the brief's `industry`
table. Step is the step of the period at which a value is final: 0 run start,
1 Pricing, 2 Demand, 3 Production and accounts, 4 Scrapping, 5 Investment, 6 Entry and
exit, 7 collector; "—" for identifiers. In a name, `{label}` stands for each key of
`HURDLE_RULES` (sorted), `{tech}` for each technique of `SHAIKH_PLANTS` and
`{parameter}` for each parameter listed under `runs`. Units: w.u. = wage units (the
money wage is the numéraire); units/period = units of output per period.
"""

INTRO = {
    "runs": "One row per run.",
    "macro": "One row per period: the industry, the price-war flags and every check "
             "residual.",
    "groups": "One row per period and label, empty groups included. Members: the firms "
              "that produced this period plus its entrants.",
    "firms": "One row per period and firm: every firm that produced this period (leavers "
             "included, `exited` true) and the period's entrants (`born = t`).",
    "plants": "One row per period and plant in operation at the start of the period, the "
              "plants retired at step 4 included. Plants on order appear only through "
              "`order` events.",
    "events": "One row per event, sorted by (t, step, event, firm_id, plant_id).",
    "flows": "One row per period and item of the transaction-flow matrix; columns are the "
             "two sectors.",
}


def _cell(text) -> str:
    return str(text).replace("|", "\\|")


def parameter_comments(source: str) -> dict[str, str]:
    """NAME -> the comment on its line, else the comment lines just above it."""
    comments, above = {}, []
    for line in source.splitlines():
        stripped = line.strip()
        if stripped.startswith("#"):
            text = stripped.lstrip("#").strip()
            above = [] if text.startswith("---") else above + [text]
            continue
        match = re.match(r"([A-Z][A-Z0-9_]*)\s*:", line)
        if match:
            inline = line.split("#", 1)[1].strip() if "#" in line else ""
            comments[match.group(1)] = inline or " ".join(above)
        if not stripped or match:
            above = []
    return comments


def render() -> str:
    lines = [HEADER]
    for table in TABLES:
        lines += [f"## `{table}`", "", INTRO[table], "",
                  "| Name | Meaning | Unit | Step | Mechanism | Phase |",
                  "| --- | --- | --- | --- | --- | --- |"]
        for c in SCHEMA[table]:
            step = "—" if c.step is None else c.step
            lines.append(f"| `{c.name}` | {_cell(c.meaning)} | {_cell(c.unit)} | {step} | "
                         f"{c.mechanism} | {c.phase} |")
        lines.append("")
        if table == "runs":
            comments = parameter_comments(Path(parameters.__file__).read_text())
            lines += ["Parameters stored in `runs` (`{parameter}` and the aliases above):",
                      "", "| Column | Parameter | Meaning (comment in parameters.py) |",
                      "| --- | --- | --- |"]
            for name, column in parameter_columns(parameters).items():
                alias = " (alias)" if name in RUN_ALIASES else ""
                lines.append(f"| `{column}`{alias} | `{name}` | "
                             f"{_cell(comments.get(name, ''))} |")
            lines.append("")
    return "\n".join(lines)


def main() -> None:
    TARGET.write_text(render())
    print(f"Written {TARGET.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
